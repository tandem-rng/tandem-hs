#!/usr/bin/env python3
"""Haskell fixtures for tests/Main.hs from the specification's vectors.json, tandem-c's
cross-check headers and tandem-cuda's fill headers.

    python3 tools/gen_fixtures.py ../tandem-spec/vectors.json ../tandem-c/tests ../tandem-cuda/tests \
      > tests/Fixtures.hs

Floats are written as their bit patterns, so the tests compare bits.
"""
import json
import re
import struct
import sys
from fractions import Fraction

vectors_path, c_tests, cuda_tests = sys.argv[1:4]


def header(name, tests=c_tests):
    with open(f"{tests}/{name}") as f:
        text = f.read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def initializer(text, name):
    """The brace initializer of array `name` as nested lists of number strings."""
    m = re.search(rf"\b{name}\s*\[[^\]]*\]\s*=\s*\{{", text)
    tokens = re.findall(r"[{},]|[^\s{},]+", text[m.end() - 1 :])
    stack, out = [[]], None
    for t in tokens:
        if t == "{":
            stack.append([])
        elif t == "}":
            done = stack.pop()
            stack[-1].append(done)
            if len(stack) == 1:
                out = stack[0][0]
                break
        elif t != ",":
            stack[-1].append(t)
    return out


def scalar(text, name):
    return re.search(rf"\b{name}\s*=\s*([0-9]+)", text).group(1)


def integer(s):
    return int(s.rstrip("uUlL"), 0)


def f64_bits(s):
    return struct.unpack("<Q", struct.pack("<d", float(s)))[0]


def f32_bits(s):
    """The bits of the float nearest the decimal `s`, rounding the exact value once."""
    exact = Fraction(s.rstrip("fF"))
    guess = struct.unpack("<I", struct.pack("<f", float(exact)))[0]

    def value(bits):
        return Fraction(struct.unpack("<f", struct.pack("<I", bits))[0])

    near = [b for b in (guess - 1, guess, guess + 1) if 0 <= b < 0x7F800000 or b >= 0x80000000]
    return min(near, key=lambda b: (abs(value(b) - exact), b & 1))


def hs_list(xs, fmt):
    return "[" + ", ".join(fmt(x) for x in xs) + "]"


def hex32(x):
    return f"0x{x:08x}"


def hex64(x):
    return f"0x{x:016x}"


def quad(words):
    return "Quad " + " ".join(hex32(int(w, 16) if isinstance(w, str) else w) for w in words)


out = []
emit = out.append

emit("-- Generated by tools/gen_fixtures.py from the specification's vectors.json, tandem-c's")
emit("-- cross-check headers and tandem-cuda's fill headers. Do not edit.")
emit("module Fixtures where")
emit("")
emit("import Data.Word (Word32, Word64)")
emit("import System.Random.Tandem (Quad (..))")
emit("")

# Specification vectors -------------------------------------------------------------------
